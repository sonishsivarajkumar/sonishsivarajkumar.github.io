// Function to load and render publications
let showingAll = false;
const initialPublicationCount = 5;

function loadPublications() {
    const publicationsList = document.getElementById('publications-list');
    if (!publicationsList) return;
    
    publicationsList.innerHTML = '';
    
    // Combine all publications and sort by year (newest first)
    const allPublications = [
        ...publicationsData.journal.map(pub => ({ ...pub, category: 'journal' })),
        ...publicationsData.conference.map(pub => ({ ...pub, category: 'conference' })),
        ...publicationsData.preprints.map(pub => ({ ...pub, category: 'preprints' }))
    ].sort((a, b) => b.year - a.year);
    
    // Show only first 5 publications initially
    const publicationsToShow = showingAll ? allPublications : allPublications.slice(0, initialPublicationCount);
    
    publicationsToShow.forEach(pub => {
        const pubElement = createPublicationElement(pub);
        publicationsList.appendChild(pubElement);
    });
    
    // Add "See More" / "See Less" button if there are more than 5 publications
    if (allPublications.length > initialPublicationCount) {
        const seeMoreDiv = document.createElement('div');
        seeMoreDiv.className = 'see-more-container';
        seeMoreDiv.innerHTML = `
            <button class="see-more-btn" onclick="togglePublications()">
                ${showingAll ? 'See Less' : `See More (${allPublications.length - initialPublicationCount} more)`}
            </button>
        `;
        publicationsList.appendChild(seeMoreDiv);
    }
    
    // Update publication count
    updatePublicationStats();
}

function togglePublications() {
    showingAll = !showingAll;
    loadPublications();
}

// Function to create publication HTML element
function createPublicationElement(publication) {
    const pubDiv = document.createElement('div');
    pubDiv.className = 'publication-item';
    pubDiv.setAttribute('data-category', publication.category);
    
    // Create links HTML
    let linksHTML = '';
    if (publication.pdf && publication.pdf !== '#') {
        linksHTML += `<a href="${publication.pdf}" class="pub-link" target="_blank" rel="noopener">PDF</a>`;
    }
    if (publication.doi && publication.doi !== '#') {
        linksHTML += `<a href="${publication.doi}" class="pub-link" target="_blank" rel="noopener">DOI</a>`;
    }
    if (publication.code && publication.code !== '#') {
        linksHTML += `<a href="${publication.code}" class="pub-link" target="_blank" rel="noopener">Code</a>`;
    }
    if (publication.data && publication.data !== '#') {
        linksHTML += `<a href="${publication.data}" class="pub-link" target="_blank" rel="noopener">Data</a>`;
    }
    
    pubDiv.innerHTML = `
        <div class="publication-year">${publication.year}</div>
        <div class="publication-content">
            <h3 class="publication-title">${publication.title}</h3>
            <p class="publication-authors">${publication.authors}</p>
            <p class="publication-venue"><em>${publication.venue}</em>${publication.details ? ', ' + publication.details : ''}</p>
            ${linksHTML ? `<div class="publication-links">${linksHTML}</div>` : ''}
        </div>
    `;
    
    return pubDiv;
}

// Function to update publication statistics
function updatePublicationStats() {
    const totalPubs = publicationsData.journal.length + publicationsData.conference.length + publicationsData.preprints.length;
    const journalCount = publicationsData.journal.length;
    const conferenceCount = publicationsData.conference.length;
    const preprintsCount = publicationsData.preprints.length;
    
    // Update filter button text to include counts
    const filterButtons = document.querySelectorAll('.filter-btn');
    filterButtons.forEach(btn => {
        const filter = btn.getAttribute('data-filter');
        const originalText = btn.textContent.split(' (')[0]; // Remove existing count
        
        switch(filter) {
            case 'all':
                btn.textContent = `${originalText} (${totalPubs})`;
                break;
            case 'journal':
                btn.textContent = `${originalText} (${journalCount})`;
                break;
            case 'conference':
                btn.textContent = `${originalText} (${conferenceCount})`;
                break;
            case 'preprints':
                btn.textContent = `${originalText} (${preprintsCount})`;
                break;
        }
    });
}

// Load publications when DOM is ready
document.addEventListener('DOMContentLoaded', function() {
    loadPublications();
});

